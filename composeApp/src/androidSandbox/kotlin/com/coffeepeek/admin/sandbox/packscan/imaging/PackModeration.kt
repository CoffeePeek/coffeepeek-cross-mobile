package com.coffeepeek.admin.sandbox.packscan.imaging

/** Pre-moderation signals of one processed photo; each is cheap to collect from the pipeline. */
internal data class PackQuality(
    /** Mean share of each quad side lying on a real edge along it. */
    val sideSupport: Double,
    /** Width / height of the rectified bag. */
    val aspect: Double,
    /** Largest corner deviation from 90 degrees in the photo. */
    val angleDeviation: Double,
    /** Share of the frame covered by the quad. */
    val quadShare: Double,
    /** Share of the frame border covered by the subject (bag cut by the frame). */
    val borderTouch: Double,
    /** Textured subject (beans, crumbs) outside the quad, relative to the quad area. */
    val clutterOutside: Double,
    /** Share of the rectified bag regenerated by MI-GAN. */
    val repaintShare: Double,
    /** Share of the bag under strong broad glare. */
    val strongGlare: Double,
)

internal enum class PackModerationStatus { Accepted, AcceptedWithHint, Retake }

/** Reasons in the order the user should read them; the UI maps each to a string resource. */
internal enum class PackModerationReason { EdgesNotFound, NotWholeBag, TooFar, OutOfFrame, ObjectsOnBag, BagCovered, Tilted, MoveCloser, Glare }

internal data class PackModeration(val status: PackModerationStatus, val reasons: List<PackModerationReason>)

/**
 * Accept / hint / retake from [quality]. Thresholds come from 19 sample photos and 2 negatives, so they
 * are a starting point to calibrate on logged Sandbox metrics, not final values.
 */
internal fun moderate(quality: PackQuality): PackModeration {
    val retake = buildList {
        if (quality.sideSupport < 0.65 || quality.angleDeviation > 20) add(PackModerationReason.EdgesNotFound)
        if (quality.aspect !in 0.4..1.35) add(PackModerationReason.NotWholeBag)
        if (quality.quadShare < 0.08) add(PackModerationReason.TooFar)
        if (quality.borderTouch > 0.25) add(PackModerationReason.OutOfFrame)
        if (quality.clutterOutside > 0.05) add(PackModerationReason.ObjectsOnBag)
        if (quality.repaintShare > 0.10) add(PackModerationReason.BagCovered)
    }
    if (retake.isNotEmpty()) return PackModeration(PackModerationStatus.Retake, retake)
    val hints = buildList {
        if (quality.angleDeviation > 12) add(PackModerationReason.Tilted)
        if (quality.quadShare < 0.2) add(PackModerationReason.MoveCloser)
        if (quality.strongGlare > 0.2) add(PackModerationReason.Glare)
    }
    return PackModeration(if (hints.isEmpty()) PackModerationStatus.Accepted else PackModerationStatus.AcceptedWithHint, hints)
}

/** Geometry signals of the fitted [front] against its subject mask (the grid copy the scorer judged). */
internal fun frontQuality(front: FrontFit, subject: BooleanArray, width: Int, height: Int): PackQuality {
    val scorer = front.scorer
    val quad = front.quad.scaled(scorer.scale)
    var polygon = 0
    var clutter = 0
    for (y in 0 until scorer.height) {
        val span = quad.rowSpan(y, scorer.width)
        for (x in 0 until scorer.width) {
            val i = y * scorer.width + x
            if (span != null && x in span) polygon++ else if (scorer.mask[i] && scorer.textured[i]) clutter++
        }
    }
    val border = (0 until width).flatMap { listOf(it, (height - 1) * width + it) } + (0 until height).flatMap { listOf(it * width, it * width + width - 1) }
    val (w, h) = front.quad.rectangle()
    return PackQuality(
        sideSupport = scorer.supports(quad).average(),
        aspect = w / h,
        angleDeviation = front.quad.angleDeviation(),
        quadShare = polygon.toDouble() / (scorer.width * scorer.height),
        borderTouch = border.count { subject[it] }.toDouble() / border.size,
        clutterOutside = clutter.toDouble() / maxOf(polygon, 1),
        repaintShare = 0.0,
        strongGlare = 0.0,
    )
}
